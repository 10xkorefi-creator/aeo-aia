/* Blog images in the AI Accountant look: cover images and in-post figures, drawn from a short JSON description.
   Nothing is generated by an image model: every picture is a template, so the wording, the logo and the numbers
   are exact and every post looks like the same brand.

   Usage: node render.js spec.json out-dir
   spec = { post: { title, kicker, date, author: { name, role, photo } }, images: [ { id, type, ... } ] }
   types: cover (variant dark|light), range_bars, bars, cards, checklist, table, steps
   Brand rules used: white, black, grey #666666 and one accent #314DD0; Helvetica Neue (Inter where it is not installed);
   tight tracking; the A-Star mark always with the wordmark, never over a busy image. */
const fs = require('fs');
const path = require('path');
