// the mark file carries its own clear space, so it is drawn larger than the text beside it and pulled in by the same amount
const lockup = (white, size) => { const m = Math.round(size * 1.7); const pull = Math.round(size * 0.35); return `<div class="lockup"><span style="width:${m}px;height:${m}px;display:block;margin:-${pull}px -${Math.round(pull * 0.6)}px -${pull}px -${pull}px">${mark(white).replace('<svg ', `<svg style="width:${m}px;height:${m}px" `)}</span>AI Accountant</div>`; };

function cover(img, post) {
  const dark = (img.variant || 'dark') === 'dark';
  const title = img.title || post.title; const n = title.length;
  const size = n <= 38 ? 78 : n <= 60 ? 66 : n <= 85 ? 56 : n <= 115 ? 48 : 42;
  const a = post.author || {};
  const photo = inline(a.photo);
  return `<div class="cover ${dark ? 'dark' : 'light'}" id="shot"><div class="grid"></div><div class="edge"></div><div class="rules"></div><div class="col"></div><div class="cell"></div>
    <div class="top">${lockup(dark, 40)}<div class="site">aiaccountant.com</div></div>
    <div class="mid">${post.kicker ? `<div class="kicker">${esc(post.kicker)}</div>` : ''}<h1 style="font-size:${size}px">${esc(title)}</h1></div>
    <div class="by">${photo ? `<img src="${photo}" alt="">` : ''}<div><b>${esc(a.name || 'AI Accountant')}</b><span>${esc([a.role, post.date].filter(Boolean).join(' · '))}</span></div></div></div>`;
}

const money = (v, unit) => (unit || '') + Number(v).toLocaleString(unit === '₹' || unit === 'Rs ' ? 'en-IN' : 'en-US');
function frame(img, inner, cls = '') {
  return `<div class="fig ${cls}" id="shot">${img.kicker ? `<div class="kicker">${esc(img.kicker)}</div>` : ''}<h2>${esc(img.title)}</h2>${img.sub ? `<p class="sub">${esc(img.sub)}</p>` : ''}
    <div class="body">${inner}</div><footer>${lockup(false, 26)}<div class="src">${esc(img.source || '')}</div></footer></div>`;
}
function bars(img) {
  const ranged = img.type === 'range_bars';
  const max = img.max || Math.max(...img.rows.map((r) => r.max ?? r.value));
  const pct = (v) => Math.max(0, Math.min(100, (v / max) * 100));
  const rows = img.rows.map((r) => {
    const lo = ranged ? pct(r.min) : 0; const hi = pct(ranged ? r.max : r.value);
    return `<div class="row"><div class="lab">${esc(r.label)}</div><div class="track"><div class="bar${r.open ? ' open' : ''}" style="left:${lo}%;width:${Math.max(hi - lo, 0.8)}%"></div></div><div class="val">${esc(r.text || (ranged ? `${money(r.min, img.unit)} to ${money(r.max, img.unit)}` : money(r.value, img.unit)))}</div></div>`;
  }).join('');
  const ticks = [0, 0.25, 0.5, 0.75, 1].map((f) => `<span style="left:${f * 100}%">${money(Math.round(max * f), img.unit)}</span>`).join('');
  return frame(img, `<div class="bars">${rows}<div class="axis"><div></div><div class="ticks">${ticks}</div><div></div></div></div>`);
}
const cards = (img) => frame(img, `<div class="cards" style="grid-template-columns:repeat(${Math.min(img.cards.length, 4)},1fr)">${img.cards.map((c) => `<div class="card${c.us ? ' us' : ''}"><div class="h">${esc(c.head)}</div>${c.value ? `<div class="v">${esc(c.value)}${c.unit ? `<small>${esc(c.unit)}</small>` : ''}</div>` : ''}<div class="t">${esc(c.text)}</div></div>`).join('')}</div>`);
const tick = '<svg width="16" height="16" viewBox="0 0 16 16" fill="none" stroke="#fff" stroke-width="2.4" stroke-linecap="round" stroke-linejoin="round"><path d="m3.5 8.5 3 3 6-7"/></svg>';
const checklist = (img) => frame(img, `<ul class="check">${img.items.map((x) => `<li><i>${tick}</i><span>${esc(x)}</span></li>`).join('')}</ul>`);
const table = (img) => frame(img, `<table><thead><tr>${img.columns.map((c) => `<th>${esc(c)}</th>`).join('')}</tr></thead><tbody>${img.rows.map((r, i) => `<tr class="${img.highlight === i ? 'us' : ''}">${r.map((c) => `<td>${esc(c)}</td>`).join('')}</tr>`).join('')}</tbody></table>`);
const steps = (img) => frame(img, `<div class="steps">${img.steps.map((s, i) => `<div class="step"><div class="n">${i + 1}</div><div><b>${esc(s.head)}</b>${s.text ? `<span>${esc(s.text)}</span>` : ''}</div></div>`).join('')}</div>`);
const MAKE = { cover, range_bars: bars, bars, cards, checklist, table, steps };

(async () => {
  fs.mkdirSync(outDir, { recursive: true });
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, deviceScaleFactor: 2 });
  const done = [];
  for (const img of spec.images) {
    const make = MAKE[img.type];
    if (!make) { console.error('unknown type', img.type); continue; }
    await page.setContent(`<!doctype html><html><head><meta charset="utf-8"><style>${CSS}</style></head><body>${make(img, spec.post || {})}</body></html>`, { waitUntil: 'load' });
    const file = path.join(outDir, `${img.id}.png`);
    await page.locator('#shot').screenshot({ path: file });
    const box = await page.locator('#shot').boundingBox();
    done.push({ id: img.id, type: img.type, file, width: Math.round(box.width * 2), height: Math.round(box.height * 2), alt: img.alt || img.title || (spec.post || {}).title });
  }
  await browser.close();
  fs.writeFileSync(path.join(outDir, 'images.json'), JSON.stringify(done, null, 1));
  for (const d of done) console.log(d.id, d.type, `${d.width}x${d.height}`, d.file);
})();
