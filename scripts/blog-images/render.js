const [, , specPath, outDir = 'out'] = process.argv;
const spec = JSON.parse(fs.readFileSync(specPath, 'utf8'));
const ASSETS = path.join(__dirname, 'assets');
const mark = (white) => fs.readFileSync(path.join(ASSETS, white ? 'ai-accountant-a-star-white.svg' : 'ai-accountant-a-star.svg'), 'utf8').replace(/<\?xml[^>]*\?>|<!DOCTYPE[^>]*>/g, '');
const esc = (s) => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36';
// remote pictures (the author photo) are fetched once and placed inside the page, so rendering needs no network
function inline(url) {
  if (!url || !/^https?:/.test(url)) return url || '';
  try {
    const buf = execFileSync('curl', ['-sS', '-L', '-m', '30', '-A', UA, url], { maxBuffer: 20 * 1024 * 1024 });
    const type = /\.png(\?|$)/i.test(url) ? 'image/png' : /\.webp(\?|$)/i.test(url) ? 'image/webp' : /\.svg(\?|$)/i.test(url) ? 'image/svg+xml' : 'image/jpeg';
    return `data:${type};base64,${buf.toString('base64')}`;
  } catch { return ''; }
}

